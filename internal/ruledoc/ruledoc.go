// Package ruledoc renders docs/rules.md, one section per rule, from the rule
// table and the groundtruth types. Every example output is produced by
// running encoding/json and encoding/json/v2 when the page is rendered, so
// the page cannot disagree with the real behaviour.
package ruledoc

import (
	"bytes"
	"encoding/json"
	jsonv2 "encoding/json/v2"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"strings"

	jsonv2audit "github.com/A-RYAN-1/jsonv2-audit"
	"github.com/A-RYAN-1/jsonv2-audit/internal/groundtruth"
)

// example ties a rule to the groundtruth type that shows it.
type example struct {
	typ    string
	decode bool
	opts   []jsonv2.Options
}

var examples = map[string]example{
	"nil-slice":          {"NilSlice", false, []jsonv2.Options{jsonv2.FormatNilSliceAsNull(true)}},
	"nil-map":            {"NilMap", false, []jsonv2.Options{jsonv2.FormatNilMapAsNull(true)}},
	"nil-bytes":          {"NilBytes", false, []jsonv2.Options{jsonv2.FormatNilSliceAsNull(true)}},
	"byte-array":         {"ByteArray", false, []jsonv2.Options{json.FormatByteArrayAsArray(true)}},
	"named-byte-slice":   {"NamedByteSlice", false, []jsonv2.Options{json.FormatBytesWithLegacySemantics(true)}},
	"omitempty":          {"OmitInt", false, []jsonv2.Options{json.OmitEmptyWithLegacySemantics(true)}},
	"omitempty-struct":   {"OmitStruct", false, []jsonv2.Options{json.OmitEmptyWithLegacySemantics(true)}},
	"string-tag":         {"StringBool", false, []jsonv2.Options{json.StringifyWithLegacySemantics(true)}},
	"string-tag-ignored": {"StringSlice", false, []jsonv2.Options{json.ReportErrorsWithLegacySemantics(true)}},
	"format-tag":         {"FormatTag", false, nil},
	"duration":           {"Duration", false, []jsonv2.Options{json.FormatDurationAsNano(true)}},
	"ptr-method":         {"PtrMethod", false, []jsonv2.Options{json.CallMethodsWithLegacySemantics(true)}},
	"case-insensitive":   {"CaseFold", true, []jsonv2.Options{jsonv2.MatchCaseInsensitiveNames(true)}},
	"array-length":       {"ArrayLength", true, []jsonv2.Options{json.UnmarshalArrayFromAnyLength(true)}},
	"null-resets":        {"NullResets", true, []jsonv2.Options{json.MergeWithLegacySemantics(true)}},
	"duplicate-name":     {"DuplicateName", false, []jsonv2.Options{json.ReportErrorsWithLegacySemantics(true)}},
}

// Render returns the contents of docs/rules.md. groundtruthSrc is the path
// of internal/groundtruth/groundtruth.go, read to show each type's source.
func Render(groundtruthSrc string) (string, error) {
	src, err := typeSources(groundtruthSrc)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# Rules\n\n")
	b.WriteString("Generated by `go run ./scripts/genrules` from the rule table and the types in `internal/groundtruth`; do not edit by hand. A test fails when this file is out of date. Every output below was produced by running `encoding/json` (v1) and `encoding/json/v2` on go1.27 when the page was generated.\n\n")
	b.WriteString("Each finding links to its section here. \"Keep v1\" is the option that makes v2 behave like v1 for that rule; pass it to the v2 call, or, if you would rather accept the v2 behaviour, change the code or the data instead.\n\n")
	b.WriteString("| Rule | Applies to | Keep v1 with |\n|---|---|---|\n")
	for _, r := range jsonv2audit.Rules {
		opt := "`" + r.Option + "`"
		if r.Option == "" {
			opt = "no option"
		}
		fmt.Fprintf(&b, "| [%s](#%s) | %s | %s |\n", r.ID, r.ID, applies(r), opt)
	}
	b.WriteString("\n")
	for _, r := range jsonv2audit.Rules {
		fmt.Fprintf(&b, "## %s\n\n%s.\n\n", r.ID, upperFirst(r.Summary))
		if r.Option != "" {
			fmt.Fprintf(&b, "Keep v1 behaviour: `%s`.\n\n", r.Option)
		}
		if r.Advisory {
			b.WriteString("This rule describes a call, not a difference in output, so it has no example. See the README section on code already on v2.\n\n")
			continue
		}
		ex, ok := examples[r.ID]
		if !ok {
			return "", fmt.Errorf("rule %s has no example", r.ID)
		}
		out, err := run(ex)
		if err != nil {
			return "", fmt.Errorf("rule %s: %w", r.ID, err)
		}
		fmt.Fprintf(&b, "```go\n%s\n```\n\n%s\n", strings.Join(sourceFor(src, ex.typ), "\n\n"), out)
	}
	return b.String(), nil
}

// helpers are the types a case's type refers to, shown before it.
var helpers = map[string][]string{
	"OmitStruct": {"allOptional"},
	"PtrMethod":  {"ptrMarshaler"},
	"NullResets": {"nullInner"},
}

func sourceFor(src map[string]string, typ string) []string {
	var out []string
	for _, h := range helpers[typ] {
		out = append(out, src[h])
	}
	return append(out, src[typ])
}

func applies(r jsonv2audit.Rule) string {
	switch {
	case r.Encode && r.Decode:
		return "encode and decode"
	case r.Encode:
		return "encode"
	default:
		return "decode"
	}
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// run executes the example under v1, v2 and v2 with the option and returns
// the three results as a block of text. It fails when the option does not
// reproduce v1, so a page cannot advertise a wrong option.
func run(ex example) (string, error) {
	if ex.decode {
		c := groundtruth.Decode[ex.typ]
		show := func(kind int) (string, error) {
			v := c.New()
			var err error
			switch kind {
			case 0:
				err = json.Unmarshal([]byte(c.Input), v)
			case 1:
				err = jsonv2.Unmarshal([]byte(c.Input), v)
			default:
				err = jsonv2.Unmarshal([]byte(c.Input), v, ex.opts...)
			}
			return fmt.Sprintf("%+v%s", v, errText(err)), err
		}
		v1, _ := show(0)
		v2, _ := show(1)
		v3, _ := show(2)
		if v3 != v1 && ex.opts != nil {
			return "", fmt.Errorf("option gave %s, v1 gave %s", v3, v1)
		}
		return table(fmt.Sprintf("Decoding `%s` into the type (a value that may already hold data):", c.Input), v1, v2, v3, ex.opts != nil), nil
	}
	v, ok := groundtruth.Encode[ex.typ]
	if !ok {
		v = groundtruth.FormatTagValue
	}
	show := func(f func(any) ([]byte, error)) (string, error) {
		b, err := f(v)
		return string(b) + errText(err), err
	}
	v1, _ := show(json.Marshal)
	v2, _ := show(func(a any) ([]byte, error) { return jsonv2.Marshal(a) })
	v3, _ := show(func(a any) ([]byte, error) { return jsonv2.Marshal(a, ex.opts...) })
	if v3 != v1 && ex.opts != nil {
		return "", fmt.Errorf("option gave %s, v1 gave %s", v3, v1)
	}
	return table("Marshaling the value:", v1, v2, v3, ex.opts != nil), nil
}

func errText(err error) string {
	if err == nil {
		return ""
	}
	// v2 picks "cannot" or "unable to" at random so nobody matches error
	// text; fix one wording so the page is reproducible.
	return "  (error: " + strings.ReplaceAll(err.Error(), "unable to ", "cannot ") + ")"
}

func table(intro, v1, v2, v3 string, hasOpt bool) string {
	s := intro + "\n\n| | Result |\n|---|---|\n"
	s += "| `encoding/json` (v1) | `" + esc(v1) + "` |\n"
	s += "| `encoding/json/v2` | `" + esc(v2) + "` |\n"
	if hasOpt {
		s += "| v2 with the option | `" + esc(v3) + "` |\n"
	}
	return s + "\n"
}

func esc(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// typeSources returns the printed declaration of every type in the file.
func typeSources(path string) (map[string]string, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	methods := map[string][]string{}
	defer func() {
		for t, ms := range methods {
			if _, ok := out[t]; ok {
				out[t] += "\n\n" + strings.Join(ms, "\n\n")
			}
		}
	}()
	for _, d := range f.Decls {
		if fd, ok := d.(*ast.FuncDecl); ok && fd.Recv != nil && len(fd.Recv.List) == 1 {
			recv := fd.Recv.List[0].Type
			if star, ok := recv.(*ast.StarExpr); ok {
				recv = star.X
			}
			if id, ok := recv.(*ast.Ident); ok {
				var buf bytes.Buffer
				if err := printer.Fprint(&buf, fset, fd); err != nil {
					return nil, err
				}
				methods[id.Name] = append(methods[id.Name], buf.String())
			}
			continue
		}
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, sp := range gd.Specs {
			ts := sp.(*ast.TypeSpec)
			one := &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{ts}}
			var buf bytes.Buffer
			if err := printer.Fprint(&buf, fset, one); err != nil {
				return nil, err
			}
			out[ts.Name.Name] = buf.String()
		}
	}
	return out, nil
}
